<?php

namespace Database\Seeders;

use App\Models\Inventory\InventoryCategory;
use App\Models\Inventory\InventoryItem;
use App\Models\Inventory\InventoryLocation;
use App\Models\Inventory\InventorySubcategory;
use App\Services\Inventory\InventoryStockService;
use Illuminate\Database\Seeder;
use Illuminate\Support\Facades\DB;
use RuntimeException;
use Throwable;

class InventoryStockAppSheetSeeder extends Seeder
{
    private const LEGACY_SOURCE = 'appsheet:STOCK CONS BMS';

    public function run(): void
    {
        $stockService = app(InventoryStockService::class);
        $categoryCache = [];
        $subcategoryCache = [];
        $locationCache = [];
        $createdItems = 0;
        $existingItems = 0;
        $openingBalances = 0;
        $zeroStockItems = 0;
        $skippedExistingStock = 0;
        $skippedSoftDeleted = 0;

        foreach ($this->items() as $row) {
            try {
                DB::transaction(function () use (
                    $row,
                    $stockService,
                    &$categoryCache,
                    &$subcategoryCache,
                    &$locationCache,
                    &$createdItems,
                    &$existingItems,
                    &$openingBalances,
                    &$zeroStockItems,
                    &$skippedExistingStock,
                    &$skippedSoftDeleted,
                ): void {
                    $category = $categoryCache[$row['category_code']] ??= InventoryCategory::query()->updateOrCreate(
                        ['code' => $row['category_code']],
                        [
                            'name' => $row['category_name'],
                            'description' => 'Kategori hasil migrasi STOCK CONS BMS.',
                            'is_active' => true,
                        ],
                    );

                    $subcategoryKey = $category->getKey().':'.$row['subcategory_code'];
                    $subcategory = $subcategoryCache[$subcategoryKey] ??= InventorySubcategory::query()->updateOrCreate(
                        [
                            'inventory_category_id' => $category->getKey(),
                            'name' => $row['subcategory_name'],
                        ],
                        [
                            'code' => $row['subcategory_code'],
                            'description' => 'Subkategori hasil migrasi STOCK CONS BMS.',
                            'is_active' => true,
                        ],
                    );

                    $location = $locationCache[$row['location_code']] ??= InventoryLocation::query()->updateOrCreate(
                        ['code' => $row['location_code']],
                        [
                            'name' => $row['location_name'],
                            'description' => 'Lokasi/rak hasil migrasi STOCK CONS BMS.',
                            'is_active' => true,
                        ],
                    );

                    $item = InventoryItem::withTrashed()->where('uid', $row['uid'])->first();

                    if ($item?->trashed()) {
                        $skippedSoftDeleted++;
                        $this->command?->warn("Lewati {$row['uid']}: item sudah soft deleted.");

                        return;
                    }

                    $masterAttributes = [
                        'item_type' => $row['item_type'],
                        'inventory_location_id' => $location->getKey(),
                        'inventory_category_id' => $category->getKey(),
                        'inventory_subcategory_id' => $subcategory->getKey(),
                        'type_category' => $row['type_category'],
                        'name' => $row['name'],
                        'description' => null,
                        'size' => $row['size'],
                        'unit' => $row['unit'],
                        'image_path' => null,
                        'legacy_image_path' => $row['legacy_image_path'],
                        'minimum_stock' => '0.000',
                        'is_active' => true,
                        'legacy_source' => self::LEGACY_SOURCE,
                    ];

                    if ($item === null) {
                        $item = InventoryItem::query()->create(['uid' => $row['uid'], ...$masterAttributes]);
                        $createdItems++;
                    } else {
                        // Seeder idempotent: item existing tidak ditimpa agar perubahan manual admin tetap aman.
                        $existingItems++;
                    }

                    if ($row['opening_stock'] === '0.000') {
                        $zeroStockItems++;

                        if ($row['correction_note'] !== null) {
                            $this->command?->warn("{$row['uid']}: {$row['correction_note']}");
                        }

                        return;
                    }

                    $item->refresh();
                    $hasHistory = $item->transactions()->exists();
                    $currentStockIsZero = (string) $item->current_stock === '0.000';

                    if ($hasHistory || ! $currentStockIsZero) {
                        $skippedExistingStock++;
                        $this->command?->warn("Lewati opening balance {$row['uid']}: stok/history sudah tersedia.");

                        return;
                    }

                    $context = [
                        'source' => 'seeder',
                        'reference_number' => 'APP-SHEET-STOCK-CONS-BMS:'.$row['uid'],
                        'legacy_id' => 'STOCK-CONS-BMS-ROW-'.$row['source_row'],
                        'legacy_payload' => [
                            'sheet' => 'STOCK CONS BMS',
                            'source_row' => $row['source_row'],
                            'original_uid' => $row['original_uid'],
                            'uid_corrected' => $row['uid_corrected'],
                            'loc_id' => $row['rack_code'],
                            'stock_in' => $row['legacy_stock_in'],
                            'stock_out' => $row['legacy_stock_out'],
                            'qty' => $row['legacy_qty'],
                            'spare_stock_original' => $row['legacy_spare_stock'],
                            'input_by' => $row['input_by'],
                            'correction_note' => $row['correction_note'],
                        ],
                    ];

                    if ($row['input_date'] !== null) {
                        $context['transaction_at'] = $row['input_date'];
                    }

                    $stockService->createOpeningBalance(
                        item: $item,
                        quantity: $row['opening_stock'],
                        actor: null,
                        context: $context,
                    );

                    $openingBalances++;
                });
            } catch (Throwable $exception) {
                $message = sprintf(
                    'Seeder gagal pada baris Excel %d, UID %s: %s',
                    $row['source_row'],
                    $row['uid'],
                    $exception->getMessage(),
                );

                $this->command?->error($message);

                throw new RuntimeException($message, previous: $exception);
            }
        }

        $this->command?->newLine();
        $this->command?->info('Inventory STOCK CONS BMS selesai diproses.');
        $this->command?->table(
            ['Keterangan', 'Jumlah'],
            [
                ['Item baru', $createdItems],
                ['Item existing dipertahankan', $existingItems],
                ['Opening balance dibuat', $openingBalances],
                ['Item stok nol/negatif dinormalisasi nol', $zeroStockItems],
                ['Opening balance dilewati karena stok/history tersedia', $skippedExistingStock],
                ['Item soft deleted dilewati', $skippedSoftDeleted],
            ],
        );
    }

